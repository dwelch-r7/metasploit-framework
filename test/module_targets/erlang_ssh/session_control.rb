# frozen_string_literal: true

require 'base64'
require 'digest'
require_relative 'settings'
require_relative '../druid_sessions/session_control'

# Observe the execution instance because console inline options are per-run.
class ErlangSshRunObserver
  include Msf::GeneralEventSubscriber

  def initialize(path)
    @path = path
  end

  def on_module_run(instance)
    return unless instance.fullname == ErlangSshSettings::OWNER

    options = instance.datastore.to_h.slice(*%w[CMD TARGET PAYLOAD RHOST RHOSTS RPORT AutoCheck SSH_IDENT LHOST LPORT])
    command = options.delete('CMD')
    row = { owner: instance.fullname, object_id: instance.object_id, options: options, command_base64: command.is_a?(String) ? Base64.strict_encode64(command) : nil }
    File.open(@path, 'a') { |file| file.puts(JSON.generate(row)) }
  end
end

# Real handler/session APIs only. The observer records completed bootstrap.
module ErlangSshSessionControl
  PAYLOADS = ErlangSshSettings::PAYLOADS

  def self.install(framework)
    observation = DruidSessionControl.install(framework)
    path = File.join(File.dirname(Msf::Config.config_directory), 'effective-run-options.jsonl')
    File.write(path, '')
    framework.events.add_general_subscriber(ErlangSshRunObserver.new(path))
    observation.merge(effective_run_options_path: path)
  end

  def self.cached_command(job, expected)
    raise ArgumentError, 'Unexpected calibration payload' unless PAYLOADS.include?(expected)

    handler, payload = job.ctx
    raise ArgumentError, 'Unexpected calibration handler' unless handler.fullname == 'exploit/multi/handler' && payload.refname == expected && handler.payload_instance.equal?(payload)

    # Read the command already generated by ExploitDriver; do not regenerate it.
    command = handler.payload.encoded
    raise ArgumentError, 'Missing generated command' unless command.is_a?(String) && !command.empty?

    { payload: payload.refname, command_base64: Base64.strict_encode64(command), command_sha256: Digest::SHA256.hexdigest(command) }
  end

  def self.proof(framework, identifier, path, marker)
    raise ArgumentError, 'Unexpected lab proof path' unless path.match?(%r{\A/tmp/module-target-erlang/session-[a-z0-9_-]+\z})
    raise ArgumentError, 'Unexpected lab marker' unless marker.match?(/\Aerlang_[a-z0-9_]+\z/)

    session = framework.sessions.fetch(identifier)
    if session.type == 'meterpreter'
      pid = session.sys.process.getpid
      identity = session.sys.config.getuid
      handle = session.fs.file.new(path, 'wb')
      begin
        written = handle.write(marker)
      ensure
        handle.close
      end
      raise IOError, 'Incomplete remote proof write' unless written == marker.bytesize
    elsif session.type == 'shell'
      identity = session.shell_command_token("printf %s #{marker} > #{path};printf '\\nERLANG_PID=%s UID=%s\\n' $$ $(id -u)")
      pid = identity.to_s[/^ERLANG_PID=(\d+) UID=\d+\r?$/, 1]
      raise IOError, 'Remote shell did not return its PID' unless pid
    else
      raise ArgumentError, "Unsupported session type #{session.type}"
    end
    { id: identifier, type: session.type, owner: session.via_exploit, payload: session.via_payload, db_id: session.db_record&.id, pid: pid.to_i, identity: identity, peer: session.tunnel_peer }
  end
end
